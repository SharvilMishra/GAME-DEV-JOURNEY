#include <iostream>
using namespace std;
int main(){
    int num = 79;
    do{
        cout << num<< endl;
        num+=79;

    }while(num<=678);
}
/*  do-while loop is used to print the multiples of 79 starting from 79 
until it reaches or exceeds 678. The loop executes at least once,
 and then continues to execute as long as the condition (num <= 678) is true. */